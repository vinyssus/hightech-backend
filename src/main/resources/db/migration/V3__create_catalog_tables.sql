-- =====================================================================
--  HITECH DZ - Catalogue (catégories, marques, produits), avis, favoris,
--  commandes minimales pour la réservation de stock
-- =====================================================================

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(120)             NOT NULL,
    name        VARCHAR(80)              NOT NULL,
    icon        VARCHAR(20)              NOT NULL DEFAULT 'tv',
    position    INTEGER                  NOT NULL DEFAULT 0,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_categories_slug UNIQUE (slug),
    CONSTRAINT ck_categories_icon CHECK (icon IN ('laptop', 'smartphone', 'headphones', 'router', 'tv', 'harddrive'))
);

CREATE TABLE category_subs (
    category_id BIGINT      NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
    position    INTEGER     NOT NULL,
    name        VARCHAR(80) NOT NULL,
    PRIMARY KEY (category_id, position)
);

CREATE TABLE brands (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug            VARCHAR(80)              NOT NULL,
    name            VARCHAR(60)              NOT NULL,
    name_key        VARCHAR(60)              NOT NULL,   -- nom en minuscules : unicité insensible à la casse
    logo_url        VARCHAR(500),
    logo_public_id  VARCHAR(255),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_brands_slug UNIQUE (slug),
    CONSTRAINT uk_brands_name_key UNIQUE (name_key)
);

CREATE TABLE products (
    id             VARCHAR(36)              PRIMARY KEY,
    slug           VARCHAR(220)             NOT NULL,
    name           VARCHAR(200)             NOT NULL,
    description    VARCHAR(5000),
    -- NULL possible uniquement pour un produit supprimé logiquement dont la catégorie/marque a été supprimée
    brand_id       BIGINT                   REFERENCES brands (id) ON DELETE SET NULL,
    category_id    BIGINT                   REFERENCES categories (id) ON DELETE SET NULL,
    price          BIGINT                   NOT NULL,
    old_price      BIGINT,
    rating         DOUBLE PRECISION         NOT NULL DEFAULT 0,
    reviews_count  INTEGER                  NOT NULL DEFAULT 0,
    sold           INTEGER                  NOT NULL DEFAULT 0,
    stock          INTEGER                  NOT NULL DEFAULT 0,
    is_new         BOOLEAN                  NOT NULL DEFAULT TRUE,
    status         VARCHAR(20)              NOT NULL,
    search_text    VARCHAR(1000)            NOT NULL,   -- texte normalisé (sans accents) pour la recherche
    version        BIGINT                   NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at     TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_products_slug UNIQUE (slug),
    CONSTRAINT ck_products_price CHECK (price > 0),
    CONSTRAINT ck_products_stock CHECK (stock >= 0),
    CONSTRAINT ck_products_status CHECK (status IN ('PUBLISHED', 'DRAFT'))
);

CREATE INDEX idx_products_listing  ON products (status, deleted_at);
CREATE INDEX idx_products_category ON products (category_id);
CREATE INDEX idx_products_brand    ON products (brand_id);
CREATE INDEX idx_products_price    ON products (price);
CREATE INDEX idx_products_sold     ON products (sold);
CREATE INDEX idx_products_created  ON products (created_at);

CREATE TABLE product_specs (
    product_id  VARCHAR(36)  NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    position    INTEGER      NOT NULL,
    spec_key    VARCHAR(100) NOT NULL,
    spec_value  VARCHAR(500) NOT NULL,
    PRIMARY KEY (product_id, position)
);

CREATE TABLE product_images (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  VARCHAR(36)  NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    url         VARCHAR(500) NOT NULL,
    public_id   VARCHAR(255),
    position    INTEGER      NOT NULL,
    width       INTEGER,
    height      INTEGER
);

CREATE INDEX idx_product_images_product   ON product_images (product_id);
CREATE INDEX idx_product_images_public_id ON product_images (public_id);

CREATE TABLE product_variants (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   VARCHAR(36) NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    sku          VARCHAR(80) NOT NULL,
    color        VARCHAR(40),
    color_hex    VARCHAR(9),
    capacity     VARCHAR(40),
    ram          VARCHAR(40),
    price_delta  BIGINT      NOT NULL DEFAULT 0,
    stock        INTEGER     NOT NULL DEFAULT 0,
    position     INTEGER     NOT NULL DEFAULT 0,
    version      BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uk_product_variants_sku UNIQUE (sku),
    CONSTRAINT ck_product_variants_stock CHECK (stock >= 0)
);

CREATE INDEX idx_product_variants_product ON product_variants (product_id);

CREATE TABLE reviews (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     VARCHAR(36)              NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    user_id        UUID                     REFERENCES users (id) ON DELETE SET NULL,
    author_name    VARCHAR(40)              NOT NULL,
    author_city    VARCHAR(60),
    rating         INTEGER                  NOT NULL,
    title          VARCHAR(120)             NOT NULL,
    body           VARCHAR(3000)            NOT NULL,
    verified       BOOLEAN                  NOT NULL DEFAULT FALSE,
    helpful_count  INTEGER                  NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_reviews_product_user UNIQUE (product_id, user_id),
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE INDEX idx_reviews_product ON reviews (product_id);

CREATE TABLE review_helpful_votes (
    review_id   BIGINT                   NOT NULL REFERENCES reviews (id) ON DELETE CASCADE,
    user_id     UUID                     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (review_id, user_id)
);

CREATE TABLE favorites (
    user_id     UUID                     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    product_id  VARCHAR(36)              NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (user_id, product_id)
);

-- Commandes minimales : réservation de stock et copie des lignes au moment de l'achat.
-- Le module Commandes (paiement, livraison, API client) viendra compléter ces tables.
CREATE TABLE orders (
    id          UUID                     PRIMARY KEY,
    user_id     UUID                     REFERENCES users (id) ON DELETE SET NULL,
    status      VARCHAR(30)              NOT NULL,
    subtotal    BIGINT                   NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_orders_status_expires ON orders (status, expires_at);
CREATE INDEX idx_orders_user ON orders (user_id);

CREATE TABLE order_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       UUID         NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id     VARCHAR(36)  NOT NULL,   -- pas de clé étrangère : la ligne est une copie figée
    sku            VARCHAR(80),
    name           VARCHAR(200) NOT NULL,
    variant_label  VARCHAR(120),
    image          VARCHAR(500),
    unit_price     BIGINT       NOT NULL,
    qty            INTEGER      NOT NULL
);

CREATE INDEX idx_order_items_order   ON order_items (order_id);
CREATE INDEX idx_order_items_product ON order_items (product_id);
