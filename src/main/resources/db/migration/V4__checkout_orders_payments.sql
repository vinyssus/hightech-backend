-- Historique des transitions
CREATE TABLE order_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    UUID                     NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    status      VARCHAR(30)              NOT NULL,
    label       VARCHAR(200)             NOT NULL,
    note        VARCHAR(500),
    actor       VARCHAR(80),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_order_events_order ON order_events (order_id);

-- Paiements Mobile Money
CREATE TABLE payments (
    id                  VARCHAR(48)              PRIMARY KEY,
    order_id            UUID                     NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    provider            VARCHAR(20)              NOT NULL,
    operator            VARCHAR(20)              NOT NULL,
    phone               VARCHAR(20)              NOT NULL,
    amount              BIGINT                   NOT NULL,
    currency            VARCHAR(3)               NOT NULL,
    status              VARCHAR(20)              NOT NULL,
    provider_reference  VARCHAR(120),
    idempotency_key     VARCHAR(80)              NOT NULL,
    request_hash        VARCHAR(64)              NOT NULL,
    message             VARCHAR(300),
    expires_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    last_checked_at     TIMESTAMP WITH TIME ZONE,
    version             BIGINT                   NOT NULL DEFAULT 0,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_payments_order_key UNIQUE (order_id, idempotency_key),
    CONSTRAINT uk_payments_provider_ref UNIQUE (provider, provider_reference)
);

CREATE INDEX idx_payments_order ON payments (order_id);
CREATE INDEX idx_payments_status_expires ON payments (status, expires_at);

-- Anti-rejeu des webhooks
CREATE TABLE payment_webhook_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider     VARCHAR(20)              NOT NULL,
    event_key    VARCHAR(200)             NOT NULL,
    received_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_payment_webhook_events UNIQUE (provider, event_key)
);

-- Utilisations des codes promo (limites par client)
CREATE TABLE promo_redemptions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    promo_id      BIGINT                   NOT NULL REFERENCES promo_codes (id) ON DELETE CASCADE,
    order_id      UUID                     NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    user_id       UUID,
    customer_key  VARCHAR(120)             NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_promo_redemptions_order UNIQUE (order_id)
);

CREATE INDEX idx_promo_redemptions_customer ON promo_redemptions (promo_id, customer_key);
