-- Codes promo (aucun code n'est créé : à saisir dans l'admin)
CREATE TABLE promo_codes (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                   VARCHAR(40)              NOT NULL,
    type                   VARCHAR(20)              NOT NULL,
    value                  BIGINT                   NOT NULL DEFAULT 0,
    description            VARCHAR(200),
    active                 BOOLEAN                  NOT NULL DEFAULT FALSE,
    starts_at              TIMESTAMP WITH TIME ZONE,
    ends_at                TIMESTAMP WITH TIME ZONE,
    min_subtotal           BIGINT,
    max_discount           BIGINT,
    max_uses               INTEGER,
    max_uses_per_customer  INTEGER,
    used_count             INTEGER                  NOT NULL DEFAULT 0,
    version                BIGINT                   NOT NULL DEFAULT 0,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_promo_codes_code UNIQUE (code),
    CONSTRAINT ck_promo_codes_type CHECK (type IN ('PERCENT', 'FIXED', 'FREE_SHIPPING'))
);

-- Devis de commande (identifiant opaque)
CREATE TABLE checkout_quotes (
    id            VARCHAR(48)              PRIMARY KEY,
    request_hash  VARCHAR(64)              NOT NULL,
    user_id       UUID,
    zone_id       VARCHAR(40)              NOT NULL,
    promo_code    VARCHAR(40),
    subtotal      BIGINT                   NOT NULL,
    discount      BIGINT                   NOT NULL,
    shipping      BIGINT                   NOT NULL,
    total         BIGINT                   NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_checkout_quotes_expires ON checkout_quotes (expires_at);

