-- Zones de livraison : gérées dans l'admin. Créées INACTIVES avec les valeurs de démonstration
-- du frontend : elles ne sont proposées aux clients qu'après validation et activation par l'admin.
CREATE TABLE shipping_zones (
    id            VARCHAR(40)              PRIMARY KEY,
    label         VARCHAR(80)              NOT NULL,
    fee           BIGINT                   NOT NULL,
    delay         VARCHAR(120),
    requires_city BOOLEAN                  NOT NULL DEFAULT FALSE,
    pickup        BOOLEAN                  NOT NULL DEFAULT FALSE,
    cod_allowed   BOOLEAN                  NOT NULL DEFAULT TRUE,
    active        BOOLEAN                  NOT NULL DEFAULT FALSE,
    position      INTEGER                  NOT NULL DEFAULT 0,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_shipping_zones_fee CHECK (fee >= 0)
);

