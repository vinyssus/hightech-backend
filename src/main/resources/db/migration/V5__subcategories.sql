-- =====================================================================
--  HITECH DZ - Sous-catégories rattachées aux produits
--  (les noms de category_subs sont repris par la migration Java V6)
-- =====================================================================
CREATE TABLE subcategories (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  BIGINT                   NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
    slug         VARCHAR(120)             NOT NULL,
    name         VARCHAR(80)              NOT NULL,
    position     INTEGER                  NOT NULL DEFAULT 0,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_subcategories_category_slug UNIQUE (category_id, slug)
);

CREATE INDEX idx_subcategories_category ON subcategories (category_id);

ALTER TABLE products ADD COLUMN subcategory_id BIGINT REFERENCES subcategories (id) ON DELETE SET NULL;
CREATE INDEX idx_products_subcategory ON products (subcategory_id);
