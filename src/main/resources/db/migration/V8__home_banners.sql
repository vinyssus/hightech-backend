-- =====================================================================
--  HITECH DZ - Bannières de la page d'accueil (3 emplacements)
--  Aucune donnée initiale : le site garde ses affiches par défaut tant qu'un emplacement est vide.
-- =====================================================================
CREATE TABLE home_banners (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot                    VARCHAR(20)              NOT NULL,
    image_url               VARCHAR(500)             NOT NULL,
    image_public_id         VARCHAR(255),
    mobile_image_url        VARCHAR(500),
    mobile_image_public_id  VARCHAR(255),
    alt_text                VARCHAR(150)             NOT NULL,
    link_type               VARCHAR(20)              NOT NULL DEFAULT 'NONE',
    link_value              VARCHAR(500),
    position                INTEGER                  NOT NULL DEFAULT 0,
    active                  BOOLEAN                  NOT NULL DEFAULT TRUE,
    starts_at               TIMESTAMP WITH TIME ZONE,
    ends_at                 TIMESTAMP WITH TIME ZONE,
    width                   INTEGER                  NOT NULL,
    height                  INTEGER                  NOT NULL,
    size_bytes              BIGINT                   NOT NULL,
    format                  VARCHAR(10)              NOT NULL,
    mobile_width            INTEGER,
    mobile_height           INTEGER,
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_home_banners_slot CHECK (slot IN ('MAIN', 'SIDE_TOP', 'SIDE_BOTTOM')),
    CONSTRAINT ck_home_banners_link CHECK (link_type IN ('CATEGORY', 'SUBCATEGORY', 'PRODUCT', 'URL', 'NONE')),
    CONSTRAINT ck_home_banners_position CHECK (position >= 0),
    CONSTRAINT ck_home_banners_dates CHECK (starts_at IS NULL OR ends_at IS NULL OR ends_at > starts_at)
);

CREATE INDEX idx_home_banners_slot_active_position ON home_banners (slot, active, position);
